    /// `Files '<patterns>'` for a pattern rule or the file type's description (`(null)` for a
    /// type without one), and the compiler's name or, for one without, its identifier
    /// (loader-experiments `build-rules`: 82 compiler specifications and 206 file types; gomap's
    /// `Files '*.secret' using Script`).
    static func buildRuleName(compiler: String, fileType: String, filePatterns: String?) -> String {
        let files = fileType == "pattern.proxy" ? "Files '\(filePatterns ?? "")'" : fileTypeDescriptions[fileType] ?? "(null)"
        return files + " using " + (compilerNames[compiler] ?? compiler)
    }

