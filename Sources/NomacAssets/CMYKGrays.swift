    /// A gray's sRGB components when its K is within a millionth of a measured quarter of 1/255.
    static func rgb(_ k: Double) -> [Double]? {
        let step = (k * 1020).rounded()
        guard abs(k * 1020 - step) < 1e-3, step >= 0, step <= 1020 else { return nil }
        let at = Int(step) * 3
        return table[at..<(at + 3)].map { Double($0) / 255 }
    }
